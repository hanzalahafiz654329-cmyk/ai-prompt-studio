-- AI Prompt Studio: Supabase database setup
-- Run this in Supabase Dashboard > SQL Editor.
-- Do not place your service_role key in website code.

create table if not exists public.prompts (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null check (category in ('Image Prompts','Video Prompts','Avatar Prompts','DIY & Construction','Tutorials')),
  description text default '',
  image_prompt text default '',
  video_prompt text default '',
  thumbnail_url text default '',
  youtube_url text default '',
  published boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.prompts enable row level security;

-- Public visitors can read published prompts only.
create policy "Public can read published prompts"
on public.prompts for select
to anon, authenticated
using (published = true);

-- Admin writes should be added only after enabling Supabase Auth and creating a secure admin-only policy.
-- Do NOT add a public insert/update/delete policy. That would let strangers change your prompt library.
